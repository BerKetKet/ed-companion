#!/usr/bin/env bash
# Regenerates docs/REPO_INDEX.md: raw GitHub links to every text file in the repo,
# so Claude can read the whole repo from ONE link without zips or pasted files.
# Run from anywhere inside the repo, after the last commit of a piece of work:
#   tools/repo_index.sh && git add docs/REPO_INDEX.md && git commit -m "chore: refresh repo index" && git push
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

BASE="https://raw.githubusercontent.com/BerKetKet/ed-companion/main"
OUT="docs/REPO_INDEX.md"
STAMP="$(date +%s)"      # cache-buster: changes on every run so no stale file is served
SHA="$(git rev-parse --short HEAD)"

# Text files worth reading. Excludes lock files, binaries, .gitkeep, and the index itself.
FILES="$(git ls-files \
  | grep -E '\.(md|dart|yaml|yml|kts|kt|xml|gradle|properties|json|txt|sh)$|(^|/)\.gitignore$' \
  | grep -Ev '(^|/)\.gitkeep$|\.lock$' \
  | grep -vx "$OUT" || true)"

# Files Claude must read first, in this order (only those that exist).
FIRST="docs/PROJECT_STATE.md
docs/WORKING_STYLE.md
docs/ROLES_AND_WORKFLOW.md
docs/DECISIONS.md
docs/VISION.md
docs/ARCHITECTURE.md
docs/ROADMAP.md
docs/CLAUDE_START.md
docs/BRIEF_TEMPLATE.md
GEMINI.md
README.md
docs/LOG.md"

{
  echo "# Repo index"
  echo
  echo "Generated by tools/repo_index.sh. Do not edit by hand."
  echo "Generated at commit $SHA (the commit that adds this index may be one newer)."
  echo
  echo "For Claude: fetch EVERY link below, completely, in the order given, before reviewing or deciding."
  echo "The v= number only defeats caching. Count the links and report how many you fetched."
  echo
  echo "## Read first, in this order"
  COUNT=0
  while IFS= read -r f; do
    if printf '%s\n' "$FILES" | grep -qx "$f"; then
      echo "- $f : $BASE/$f?v=$STAMP"
      COUNT=$((COUNT+1))
    fi
  done <<< "$FIRST"
  echo
  echo "## Everything else (briefs, reports, workflow, code, tests)"
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    if ! printf '%s\n' "$FIRST" | grep -qx "$f"; then
      echo "- $f : $BASE/$f?v=$STAMP"
      COUNT=$((COUNT+1))
    fi
  done <<< "$(printf '%s\n' "$FILES" | sort)"
  echo
  echo "Total links: $COUNT"
} > "$OUT"

echo "Wrote $OUT ($(grep -c '^- ' "$OUT") links)."
echo "Raw link to give Claude: $BASE/$OUT?v=$STAMP"
